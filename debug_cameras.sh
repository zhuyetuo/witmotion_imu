#!/bin/bash
# 调试用：只看画面，一个文件都不写。
#
#   ./debug_cameras.sh                      按 sites/.current 的场地
#   SITE=影棚 ./debug_cameras.sh            指定场地
#   CAMS="2" ./debug_cameras.sh             只开一路，定位是哪个摄像头有问题
#   ./debug_cameras.sh --backend dshow      换 OpenCV 后端
#
# 干什么用的：
#   - 认清楚系统里的「摄像头 0」是哪个单间/哪个机位
#   - 晃一下项圈，看画面上哪个 imu 编号的 Hz 跟着动，确认设备戴在谁身上
#   - 摄像头打不开、崩了，反复试参数（每次都不落盘，硬盘上不留垃圾）
#
# 为什么单独一个脚本，而不是让你在 record_multicam.sh 上加开关：
#   record_multicam.sh 是每天在跑的、要稳的那条路。调试的东西一件件往它身上加，
#   加到后来那条稳定命令自己就不灵了——已经发生过一次：CAMS 的默认值被我删掉，
#   一条用了很久的纯环境变量命令就去开了它根本没要过的第三个摄像头，直接崩。
#   所以调试从这里进，那边只管录。
#
# 这个脚本本身没有任何逻辑，就是带着 DEBUG=1 去调 record_multicam.sh——
# 两边共用同一套场地解析、设备解析、参数拼装。复制一份出来早晚会跟那边走岔，
# 而走岔的表现是"调试时是好的，正式录就不对"，最难查。
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")"

echo "════════════════════════════════════════════════════════════"
echo "  调试模式：不保存任何文件，只开画面"
echo "  退出：q + 回车，或者 Ctrl-C"
echo "════════════════════════════════════════════════════════════"

# PREVIEW 不给覆盖：不看画面的话这个脚本没有存在的意义
DEBUG=1 PREVIEW=1 exec ./record_multicam.sh "$@"
